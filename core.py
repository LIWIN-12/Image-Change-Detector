"""Pure image-forensics helpers. No Streamlit imports, so they are testable."""

from __future__ import annotations

import io
from dataclasses import dataclass, field

import cv2
import numpy as np
from PIL import Image

MAX_EDGE = 1600
MODEL_URL = ("https://huggingface.co/onnx-community/"
             "SMOGY-Ai-images-detector-ONNX/resolve/main/onnx/model_int8.onnx")
MODEL_FILE = "model_int8.onnx"
IMAGE_SIZE = (224, 224)
MODEL_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
MODEL_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)
AI_MARKERS = (
    "stable diffusion", "comfyui", "automatic1111", "sdxl", "dalle",
    "midjourney", "firefly", "flux", "generated by",
)


def prepare(image, max_edge: int = MAX_EDGE) -> np.ndarray:
    """Return an RGB uint8 array, downscaled to a safe size."""
    if isinstance(image, Image.Image):
        array = np.array(image.convert("RGB"))
    else:
        array = np.asarray(image)
        if array.ndim == 2:
            array = cv2.cvtColor(array, cv2.COLOR_GRAY2RGB)
        elif array.shape[2] == 4:
            array = cv2.cvtColor(array, cv2.COLOR_RGBA2RGB)
    scale = min(1.0, max_edge / max(array.shape[:2]))
    if scale < 1.0:
        size = (round(array.shape[1] * scale), round(array.shape[0] * scale))
        array = cv2.resize(array, size, interpolation=cv2.INTER_AREA)
    return array


@dataclass
class DiffResult:
    marked: np.ndarray
    mask: np.ndarray
    diff: np.ndarray
    regions: list[dict]
    aligned: bool


def align_pair(before: np.ndarray, after: np.ndarray) -> tuple[np.ndarray, bool]:
    """Align `after` to `before` with translational/rotational ECC."""
    if after.shape[:2] != before.shape[:2]:
        after = cv2.resize(after, (before.shape[1], before.shape[0]),
                           interpolation=cv2.INTER_AREA)
    template = cv2.cvtColor(before, cv2.COLOR_RGB2GRAY)
    incoming = cv2.cvtColor(after, cv2.COLOR_RGB2GRAY)
    warp = np.eye(2, 3, dtype=np.float32)
    criteria = (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 60, 1e-6)
    try:
        score, warp = cv2.findTransformECC(
            template, incoming, warp, cv2.MOTION_EUCLIDEAN, criteria, None, 5
        )
    except cv2.error:
        return after, False
    if not np.isfinite(score) or score < 0.5:
        return after, False
    flags = cv2.INTER_LINEAR | cv2.WARP_INVERSE_MAP
    aligned = cv2.warpAffine(after, warp, (before.shape[1], before.shape[0]),
                             flags=flags, borderMode=cv2.BORDER_REFLECT)
    return aligned, True


def detect_changes(before_img, after_img, threshold: int = 30,
                   min_area: int = 100, align: bool = True) -> DiffResult:
    """Detect changed regions; count only regions that are actually drawn."""
    before = prepare(before_img)
    after = prepare(after_img)
    aligned = False
    if align:
        after, aligned = align_pair(before, after)

    gray_before = cv2.cvtColor(before, cv2.COLOR_RGB2GRAY)
    gray_after = cv2.cvtColor(after, cv2.COLOR_RGB2GRAY)
    gray_before = cv2.GaussianBlur(gray_before, (5, 5), 0)
    gray_after = cv2.GaussianBlur(gray_after, (5, 5), 0)

    diff = cv2.absdiff(gray_before, gray_after)
    _, mask = cv2.threshold(diff, threshold, 255, cv2.THRESH_BINARY)
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))

    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    kept = [c for c in contours if cv2.contourArea(c) > min_area]

    marked = after.copy()
    regions = []
    for contour in kept:
        x, y, w, h = cv2.boundingRect(contour)
        cv2.rectangle(marked, (x, y), (x + w, y + h), (255, 0, 0), 2)
        regions.append({
            "x": x, "y": y, "w": w, "h": h,
            "area": int(cv2.contourArea(contour)),
            "mean_diff": round(float(diff[y:y + h, x:x + w].mean()), 1),
        })
    regions.sort(key=lambda r: r["area"], reverse=True)
    return DiffResult(marked, mask, diff, regions, aligned)


def error_level_analysis(image) -> tuple[np.ndarray, float]:
    """Amplified difference between the upload and a JPEG Q90 re-save."""
    array = prepare(image)
    ok, encoded = cv2.imencode(".jpg", cv2.cvtColor(array, cv2.COLOR_RGB2BGR),
                               [cv2.IMWRITE_JPEG_QUALITY, 90])
    if not ok:
        raise ValueError("Could not encode image for ELA")
    resaved = cv2.cvtColor(cv2.imdecode(encoded, cv2.IMREAD_COLOR), cv2.COLOR_BGR2RGB)
    residual = cv2.absdiff(array, resaved)
    heat = np.clip(residual.astype(np.float32) * 20, 0, 255).astype(np.uint8)
    score = float(np.max(heat, axis=2).mean())
    return heat, score


def copy_move(image, min_distance: int = 40, max_distance: float = 24.0) -> list:
    """Find ORB keypoint pairs that look like duplicated patches."""
    gray = cv2.cvtColor(prepare(image), cv2.COLOR_RGB2GRAY)
    keypoints, descriptors = cv2.ORB_create(nfeatures=2000).detectAndCompute(gray, None)
    if descriptors is None or len(keypoints) < 2:
        return []
    # k=3 because each descriptor's closest "match" is always itself.
    matches = cv2.BFMatcher(cv2.NORM_HAMMING).knnMatch(descriptors, descriptors, k=3)
    pairs = set()
    for row in matches:
        for candidate in row:
            if candidate.queryIdx == candidate.trainIdx:
                continue
            if candidate.distance > max_distance:
                continue
            a = keypoints[candidate.queryIdx].pt
            b = keypoints[candidate.trainIdx].pt
            if np.hypot(a[0] - b[0], a[1] - b[1]) < min_distance:
                continue
            pairs.add(tuple(sorted(((round(a[0]), round(a[1])),
                                    (round(b[0]), round(b[1]))))))
    return sorted(pairs)


def noise_map(image, block: int = 16) -> tuple[np.ndarray, float]:
    """Block-wise high-frequency noise, plus max/median inconsistency ratio."""
    gray = cv2.cvtColor(prepare(image), cv2.COLOR_RGB2GRAY).astype(np.float32)
    high_pass = np.abs(gray - cv2.GaussianBlur(gray, (0, 0), 1.0))
    height, width = high_pass.shape
    out = np.zeros((height, width), np.float32)
    for y in range(0, height, block):
        for x in range(0, width, block):
            tile = high_pass[y:y + block, x:x + block]
            out[y:y + block, x:x + block] = tile.std()
    ratio = float(out.max() / max(float(np.median(out)), 1e-6))
    return out, ratio


def detector_input(image) -> np.ndarray:
    """Resize and normalize an image for the ONNX Swin detector."""
    array = cv2.resize(prepare(image), IMAGE_SIZE, interpolation=cv2.INTER_CUBIC)
    values = array.astype(np.float32) / 255.0
    values = (values - MODEL_MEAN) / MODEL_STD
    return values.transpose(2, 0, 1)[None].astype(np.float32)


def artificial_probability(session, image) -> float:
    """P(artificial) from an ONNX session; label 0 is artificial."""
    tensor = detector_input(image)
    logits = session.run(None, {session.get_inputs()[0].name: tensor})[0]
    shifted = logits - logits.max(axis=1, keepdims=True)
    exp = np.exp(shifted)
    probabilities = exp / exp.sum(axis=1, keepdims=True)
    return float(probabilities[0, 0])


@dataclass
class Provenance:
    hits: list[str] = field(default_factory=list)

    @property
    def strong(self) -> bool:
        return bool(self.hits)


def read_provenance(raw: bytes) -> Provenance:
    """Look for AI tool fingerprints in PNG chunks, EXIF, XMP and C2PA bytes."""
    hits: list[str] = []
    try:
        image = Image.open(io.BytesIO(raw))
        for key in ("parameters", "workflow", "prompt", "Comment", "Software"):
            value = image.info.get(key)
            if isinstance(value, bytes):
                value = value.decode("utf-8", "ignore")
            if not value:
                continue
            text = str(value)
            lowered = text.lower()
            if key in ("parameters", "workflow", "prompt") or any(
                marker in lowered for marker in AI_MARKERS
            ):
                hits.append(f"{key}: {text[:120]}")
        software = str(image.getexif().get(305, ""))
        if any(marker in software.lower() for marker in AI_MARKERS):
            hits.append(f"EXIF Software: {software}")
    except Exception:
        pass

    lowered_bytes = raw.lower()
    for marker, label in ((b"c2pa", "C2PA manifest"),
                          (b"jumbf", "JUMBF provenance"),
                          (b"trainedalgorithmicmedia", "XMP generative-media flag")):
        if marker in lowered_bytes:
            hits.append(label)
    return Provenance(hits)


def ai_heuristics(image) -> tuple[list[str], float, float]:
    """Two weak visual clues. Never strong evidence on their own."""
    array = prepare(image)
    gray = cv2.cvtColor(array, cv2.COLOR_RGB2GRAY)
    smoothness = float(cv2.Laplacian(gray, cv2.CV_64F).var())
    clipped = float(np.mean(cv2.cvtColor(array, cv2.COLOR_RGB2HSV)[:, :, 1] > 250))
    flags = []
    if smoothness < 60:
        flags.append("unusually smooth texture")
    if clipped > 0.05:
        flags.append("many clipped-saturation pixels")
    return flags, smoothness, clipped


def ai_band(provenance: Provenance, p_artificial: float | None,
            flags: list[str]) -> tuple[str, str]:
    """Turn three imperfect signals into an honest confidence band."""
    if provenance.strong:
        return "Strong", "The file itself contains an AI-tool or provenance tag."
    if p_artificial is None:
        return "Unknown", "Detector unavailable; only file tags were checked."
    if p_artificial >= 0.90 or (p_artificial >= 0.75 and flags):
        return "Moderate", "Detector strongly leans artificial; no file tag found."
    if p_artificial >= 0.65 or flags:
        return "Weak", "Weak visual signals only."
    return "No evidence", "No tag and no strong visual signal."
